#!/bin/bash
# Сквозная проверка калибровки: пиксель -> координаты руки.
#
# Перед запуском проверяется, что камера в рабочем состоянии: драйвер поднят,
# мёртвой области нет.
# Дополнительно сверяется положение камеры с эталоном — этот инструмент
# опирается на калибровку, а сдвиг камеры делает её молча неверной.
# Пропустить проверку: --skip-preflight
#
# На время сверки стол должен быть ПУСТОЙ: доска гасит ИК, глубина под ней
# проваливается, и сверка ложно решает, что камеру сдвинули. Скрипт сам
# попросит положить доску, когда сверка закончится.
set -e
HERE="$(dirname "$(readlink -f "$0")")"
source "$HERE/../_lib/env.sh"
source "$HERE/../_lib/preflight.sh"

ARGS=(); SKIP=0
for a in "$@"; do
    case "$a" in
        --skip-preflight) SKIP=1 ;;
        *) ARGS+=("$a") ;;
    esac
done

robohand_env ros
cd "$ROBOHAND_ROOT"
if [ "$SKIP" -eq 0 ]; then
    echo "Стол пока должен быть ПУСТОЙ — доску положишь, когда попрошу."
    robohand_camera_ready --verify-zone
fi
exec env "${ROBOHAND_ENV[@]}" python3 tools/calib/check.py "${ARGS[@]}"
